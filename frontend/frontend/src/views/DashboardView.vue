<script setup>
import { ref, onMounted } from 'vue'
import axios from 'axios'

const collectionsCount = ref(0)
const videosCount = ref(0)
const audioCount = ref(0)
const imagesCount = ref(0)
const collections = ref([])

const BACKEND_URL = import.meta.env.VITE_APP_BACKEND_URL || 'http://localhost:8000'

const fetchStats = async () => {
  try {
    const [collectionsRes, videosRes, audioRes, imagesRes] = await Promise.all([
      axios.get(`${BACKEND_URL}/videodb/collection`),
      axios.get(`${BACKEND_URL}/videodb/collection/default/video`),
      axios.get(`${BACKEND_URL}/videodb/collection/default/audio`),
      axios.get(`${BACKEND_URL}/videodb/collection/default/image`)
    ])

    collectionsCount.value = collectionsRes.data.length
    videosCount.value = videosRes.data.length
    audioCount.value = audioRes.data.length
    imagesCount.value = imagesRes.data.length
    collections.value = collectionsRes.data
  } catch (error) {
    console.error('Failed to fetch stats:', error)
  }
}

onMounted(() => {
  fetchStats()
})
</script>